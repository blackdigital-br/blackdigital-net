namespace BlackDigital
{
    /// <summary>
    /// Specifies a comparison operator used for value validation.
    /// </summary>
    public enum Symbol
    {
        /// <summary>
        /// Represents an equality comparison.
        /// </summary>
        Equal,

        /// <summary>
        /// Represents an inequality comparison.
        /// </summary>
        NotEqual,

        /// <summary>
        /// Represents a less-than comparison.
        /// </summary>
        LessThan,

        /// <summary>
        /// Represents a less-than-or-equal comparison.
        /// </summary>
        LessThanOrEqual,

        /// <summary>
        /// Represents a greater-than comparison.
        /// </summary>
        GreaterThan,

        /// <summary>
        /// Represents a greater-than-or-equal comparison.
        /// </summary>
        GreaterThanOrEqual,
    }
}
